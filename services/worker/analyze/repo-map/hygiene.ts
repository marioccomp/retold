/**
 * Repository hygiene and generated-code detection.
 *
 * The scanner skips folders such as node_modules, so committed dependency
 * folders are invisible to it; hygiene looks at what git actually tracks
 * (`git ls-files`) to catch them.
 */
import { execFileSync } from "child_process";
import path from "path";

import { isExcludedFromLineCounts } from "../../contribution-stats.js";

export type HygieneFlag =
  | "node_modules"
  | "python-venv"
  | "pycache"
  | "compiled-artifacts"
  | "env-file"
  | "private-key"
  | "large-files";

export type HygieneReport = {
  flags: HygieneFlag[];
  /** flag -> number of tracked files behind it */
  counts: Partial<Record<HygieneFlag, number>>;
  /** flag -> a few example paths */
  examples: Partial<Record<HygieneFlag, string[]>>;
};

const COMPILED_EXTENSIONS = new Set([".class", ".o", ".obj", ".exe", ".dll", ".pyc", ".jar", ".so"]);
const ENV_FILE = /(^|\/)\.env(\.[\w-]+)?$/;
const ENV_TEMPLATE = /\.(example|sample|template|dist|defaults)$/;
const PRIVATE_KEY = /(^|\/)(id_rsa|id_dsa|id_ecdsa|id_ed25519)$|\.(pem|key|p12|pfx)$/;
/** Test fixtures legitimately contain fake .env files and keys. */
const FIXTURE_DIRS = new Set(["test", "tests", "__tests__", "spec", "fixtures", "__fixtures__", "testdata", "test_data", "examples"]);

function classify(filePath: string): HygieneFlag | null {
  const segments = filePath.split("/");
  if (segments.includes("node_modules")) return "node_modules";
  if (segments.some((s) => s === "site-packages") || /(^|\/)pyvenv\.cfg$/.test(filePath)) {
    return "python-venv";
  }
  if (segments.includes("__pycache__")) return "pycache";
  if (COMPILED_EXTENSIONS.has(path.posix.extname(filePath).toLowerCase())) return "compiled-artifacts";
  const inFixtures = segments.slice(0, -1).some((s) => FIXTURE_DIRS.has(s.toLowerCase()));
  if (inFixtures) return null;
  if (ENV_FILE.test(filePath) && !ENV_TEMPLATE.test(filePath)) return "env-file";
  if (PRIVATE_KEY.test(filePath) && !/public|\.pub$/.test(filePath)) return "private-key";
  return null;
}

/**
 * @param trackedFiles  files tracked by git (POSIX paths)
 * @param fileSizes     sizes in bytes for the files the scanner saw
 */
export function buildHygieneReport(
  trackedFiles: string[],
  fileSizes: Map<string, number> = new Map()
): HygieneReport {
  const counts: HygieneReport["counts"] = {};
  const examples: HygieneReport["examples"] = {};

  const record = (flag: HygieneFlag, filePath: string) => {
    counts[flag] = (counts[flag] ?? 0) + 1;
    const list = (examples[flag] ??= []);
    if (list.length < 3) list.push(filePath);
  };

  for (const filePath of trackedFiles) {
    const flag = classify(filePath);
    if (flag) record(flag, filePath);
  }

  for (const [filePath, size] of fileSizes) {
    if (size > 5 * 1024 * 1024) record("large-files", filePath);
  }

  // A single compiled file can be a legitimate fixture; flag real build output only.
  if ((counts["compiled-artifacts"] ?? 0) < 3) {
    delete counts["compiled-artifacts"];
    delete examples["compiled-artifacts"];
  }

  return { flags: Object.keys(counts) as HygieneFlag[], counts, examples };
}

export function listTrackedFiles(repoPath: string): string[] {
  try {
    return execFileSync("git", ["-C", repoPath, "ls-files", "-z"], {
      encoding: "utf8",
      maxBuffer: 256 * 1024 * 1024,
      stdio: ["ignore", "pipe", "ignore"],
    })
      .split("\0")
      .filter(Boolean);
  } catch {
    return [];
  }
}

const GENERATED_MARKER =
  /@generated|do not edit|auto-?generated|automatically generated|generated by|code generated .* do not edit/i;

/**
 * Generated or minified source: excluded paths (lockfiles, dist, ...), a
 * "generated" marker in the first lines, or minified-looking content.
 */
export function isGeneratedSource(filePath: string, content: string) {
  if (isExcludedFromLineCounts(filePath)) return true;

  const head = content.slice(0, 1_000).split("\n").slice(0, 5).join("\n");
  if (GENERATED_MARKER.test(head)) return true;

  const lines = content.split("\n");
  const longLines = lines.filter((line) => line.length > 500).length;
  return lines.length > 0 && longLines / lines.length > 0.2 && content.length > 5_000;
}
